export function mergeEvents(records) {
  const key = title => title.trim().toLocaleLowerCase();
  const merged = new Map(events.map(event => [key(event.title), event]));
  records.forEach(record => {
    const existing = merged.get(key(record.title));
    merged.set(key(record.title), { ...existing, ...record, image_url: record.cover_image_url || existing?.image_url || record.image_url || '' });
  });
  return [...merged.values()].sort((a, b) => b.date.localeCompare(a.date));
}

