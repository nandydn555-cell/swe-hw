const teacherKey = name => name.replace(/\s+/g, '').toLocaleLowerCase();
export function mergeTeachers(records, base = teachers) {
  const merged = new Map(base.map(t => [teacherKey(t.name), t]));
  records.forEach((record, i) => {
    const key = teacherKey(record.name);
    const existing = merged.get(key);
    merged.set(key, {
      ...existing, ...record,
      photo_url: record.photo_url || existing?.photo_url || '',
      courses: Array.isArray(record.courses) ? record.courses.join(' · ') : record.courses || existing?.courses || '',
      initials: record.name.split('.').at(-1).trim()[0],
      color: existing?.color || ['mint', 'peach', 'lavender'][i % 3]
    });
  });
  return [...merged.values()];
}

